import Foundation

/// ポイントクラウドのエクスポート形式
enum PointCloudFormat: String, CaseIterable {
    case ply = "PLY"
    case pcd = "PCD"
    case xyz = "XYZ"

    var fileExtension: String {
        switch self {
        case .ply: return "ply"
        case .pcd: return "pcd"
        case .xyz: return "xyz"
        }
    }

    var description: String {
        switch self {
        case .ply: return "Polygon File Format (PLY)"
        case .pcd: return "Point Cloud Data (PCD)"
        case .xyz: return "XYZ Text Format"
        }
    }
}

/// ポイントクラウドのエクスポーター
final class PointCloudExporter {

    // MARK: - Export Methods

    /// ポイントクラウドをファイルにエクスポート
    static func export(
        points: [PointXYZRGB],
        format: PointCloudFormat,
        to url: URL
    ) throws {
        let content: String
        switch format {
        case .ply:
            content = generatePLY(points: points)
        case .pcd:
            content = generatePCD(points: points)
        case .xyz:
            content = generateXYZ(points: points)
        }

        try content.write(to: url, atomically: true, encoding: .utf8)
    }

    /// ポイントクラウドを文字列としてエクスポート
    static func exportToString(
        points: [PointXYZRGB],
        format: PointCloudFormat
    ) -> String {
        switch format {
        case .ply:
            return generatePLY(points: points)
        case .pcd:
            return generatePCD(points: points)
        case .xyz:
            return generateXYZ(points: points)
        }
    }

    /// 録画セッションからポイントクラウドを抽出してエクスポート
    static func exportFromSession(
        sessionDir: URL,
        format: PointCloudFormat,
        aggregateAll: Bool = true
    ) throws -> URL {
        let dataURL = sessionDir.appendingPathComponent("sensor_data.jsonl")
        let outputURL = sessionDir.appendingPathComponent("pointcloud.\(format.fileExtension)")

        guard FileManager.default.fileExists(atPath: dataURL.path) else {
            throw ExportError.fileNotFound
        }

        let content = try String(contentsOf: dataURL, encoding: .utf8)
        let lines = content.components(separatedBy: "\n").filter { !$0.isEmpty }

        var allPoints: [PointXYZRGB] = []
        let decoder = JSONDecoder()

        for line in lines {
            guard let data = line.data(using: .utf8) else { continue }
            do {
                let frame = try decoder.decode(SensorFrame.self, from: data)
                if let pointCloud = frame.pointCloud {
                    if aggregateAll {
                        allPoints.append(contentsOf: pointCloud.points)
                    } else {
                        // 最後のフレームのみ使用
                        allPoints = pointCloud.points
                    }
                }
            } catch {
                // 無効な行はスキップ
                continue
            }
        }

        guard !allPoints.isEmpty else {
            throw ExportError.noPointCloudData
        }

        try export(points: allPoints, format: format, to: outputURL)
        return outputURL
    }

    // MARK: - PLY Format

    /// PLY形式のファイル内容を生成
    private static func generatePLY(points: [PointXYZRGB]) -> String {
        var output = """
        ply
        format ascii 1.0
        comment Generated by DataStreamingApp
        comment \(Date().ISO8601Format())
        element vertex \(points.count)
        property float x
        property float y
        property float z
        property uchar red
        property uchar green
        property uchar blue
        end_header

        """

        for point in points {
            output += String(format: "%.6f %.6f %.6f %d %d %d\n",
                           point.x, point.y, point.z,
                           point.r, point.g, point.b)
        }

        return output
    }

    // MARK: - PCD Format

    /// PCD形式のファイル内容を生成
    private static func generatePCD(points: [PointXYZRGB]) -> String {
        var output = """
        # .PCD v0.7 - Point Cloud Data file format
        # Generated by DataStreamingApp
        VERSION 0.7
        FIELDS x y z rgb
        SIZE 4 4 4 4
        TYPE F F F U
        COUNT 1 1 1 1
        WIDTH \(points.count)
        HEIGHT 1
        VIEWPOINT 0 0 0 1 0 0 0
        POINTS \(points.count)
        DATA ascii

        """

        for point in points {
            // RGBをパックされた整数値に変換
            let rgb = UInt32(point.r) << 16 | UInt32(point.g) << 8 | UInt32(point.b)
            output += String(format: "%.6f %.6f %.6f %u\n",
                           point.x, point.y, point.z, rgb)
        }

        return output
    }

    // MARK: - XYZ Format

    /// XYZ形式のファイル内容を生成（シンプルなテキスト形式）
    private static func generateXYZ(points: [PointXYZRGB]) -> String {
        var output = "# X Y Z R G B\n"
        output += "# Generated by DataStreamingApp\n"
        output += "# \(Date().ISO8601Format())\n"
        output += "# Points: \(points.count)\n"

        for point in points {
            output += String(format: "%.6f %.6f %.6f %d %d %d\n",
                           point.x, point.y, point.z,
                           point.r, point.g, point.b)
        }

        return output
    }
}

// MARK: - Export Error

enum ExportError: LocalizedError {
    case fileNotFound
    case noPointCloudData
    case encodingFailed

    var errorDescription: String? {
        switch self {
        case .fileNotFound:
            return "Recording file not found"
        case .noPointCloudData:
            return "No point cloud data in recording"
        case .encodingFailed:
            return "Failed to encode point cloud"
        }
    }
}

// MARK: - PointCloudSnapshot Extension

extension PointCloudSnapshot {
    /// PLY形式でエクスポート
    func toPLY() -> String {
        PointCloudExporter.exportToString(points: points, format: .ply)
    }

    /// PCD形式でエクスポート
    func toPCD() -> String {
        PointCloudExporter.exportToString(points: points, format: .pcd)
    }

    /// XYZ形式でエクスポート
    func toXYZ() -> String {
        PointCloudExporter.exportToString(points: points, format: .xyz)
    }

    /// ファイルに保存
    func save(to url: URL, format: PointCloudFormat) throws {
        try PointCloudExporter.export(points: points, format: format, to: url)
    }
}
